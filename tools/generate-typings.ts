// Generates, from the Custom Elements Manifest, the typings a consumer needs: the global tag and event maps (so
// `document.createElement("camo-button")` and `addEventListener("camo-close")` are typed), and JSX (React) and Vue
// typings for the elements. `pnpm typings` writes them; CI runs `pnpm typings:check`, which fails when a committed file is
// out of date. The manifest comes from the elements' JSDoc (`@attr`, `@slot`, `@fires`), so they are the source.
import { readFileSync, writeFileSync } from "node:fs";
import { format, resolveConfig } from "prettier";
import { generateManifest, elementsOf } from "./manifest.ts";
import type { ManifestDeclaration } from "./manifest.ts";

const root = new URL("..", import.meta.url).pathname;
const BUILTIN = new Set(["string", "number", "boolean", "null", "undefined", "unknown", "never"]);

/** The type names a text refers to (`Appearance | null` → `Appearance`), to import them. */
function typeNames(text: string): string[] {
  return (text.match(/\b[A-Z]\w*/g) ?? []).filter((n) => !BUILTIN.has(n));
}

/** The attribute's TypeScript type, from the manifest, or `string` when the analyzer found none. */
function attributeType(a: NonNullable<ManifestDeclaration["attributes"]>[number]): string {
  return a.type?.text ?? "string";
}

interface Model {
  tag: string;
  className: string;
  attributes: { name: string; type: string; description: string }[];
  events: { name: string; type: string }[];
  /** The type names each generated file needs from the package. */
  imports: { element: string; attributes: string[]; events: string[] };
}

const NATIVE = new Set(["input", "change", "click", "focus", "blur", "submit", "reset"]);

function model(d: ManifestDeclaration): Model {
  const attributes = (d.attributes ?? [])
    // `data-camo-scheme` is the provider's reflected output, not something a consumer sets.
    .filter((a) => !a.name.startsWith("data-"))
    .map((a) => ({ name: a.name, type: attributeType(a), description: a.description ?? "" }));
  // The platform's own events (`input`, `change`, …) keep their DOM types: documenting them in the manifest must not
  // retype them in the global map.
  const events = (d.events ?? [])
    .filter((e) => !NATIVE.has(e.name))
    .map((e) => ({ name: e.name, type: e.type?.text ?? "CustomEvent" }));
  const imports = {
    element: d.name,
    attributes: attributes.flatMap((a) => typeNames(a.type)),
    events: events.flatMap((e) => typeNames(e.type).filter((n) => n !== "CustomEvent")),
  };
  return { tag: d.tagName!, className: d.name, attributes, events, imports };
}

const HEADER =
  "// Generated by tools/generate-typings.ts from the Custom Elements Manifest; do not edit.\n";

const unique = (names: string[]): string[] => [...new Set(names)].sort();

/** `src/elements.ts`: the global maps, loaded with the package's main entry. */
function globals(models: Model[]): string {
  const imports = unique(models.flatMap((m) => [m.imports.element, ...m.imports.events]));
  const lines = [
    HEADER,
    `import type { ${imports.join(", ")} } from "./index.ts";\n`,
    "declare global {",
    "  interface HTMLElementTagNameMap {",
    ...models.map((m) => `    "${m.tag}": ${m.className};`),
    "  }",
    "  interface HTMLElementEventMap {",
    ...[...new Map(models.flatMap((m) => m.events).map((e) => [e.name, e])).values()].map(
      (e) => `    "${e.name}": ${e.type};`,
    ),
    "  }",
    "}\n",
    "export {};",
  ];
  return lines.join("\n");
}

const attributeLines = (m: Model, indent: string): string[] =>
  m.attributes.map(
    (a) => `${indent}${/^[a-z]+$/.test(a.name) ? a.name : `"${a.name}"`}?: ${a.type};`,
  );

/** `typings/react.d.ts`: JSX for React 19 (custom elements take attributes and properties). */
function react(models: Model[]): string {
  const imports = unique(models.flatMap((m) => [m.imports.element, ...m.imports.attributes]));
  return [
    HEADER,
    'import type { DetailedHTMLProps, HTMLAttributes } from "react";',
    `import type { ${imports.join(", ")} } from "@srctool/camouflage-core";\n`,
    "type CamoElement<T extends HTMLElement, A> = DetailedHTMLProps<HTMLAttributes<T>, T> & A;\n",
    'declare module "react" {',
    "  namespace JSX {",
    "    interface IntrinsicElements {",
    ...models.flatMap((m) => [
      `      "${m.tag}": CamoElement<${m.className}, {`,
      ...attributeLines(m, "        "),
      "      }>;",
    ]),
    "    }",
    "  }",
    "}\n",
    "export {};",
  ].join("\n");
}

/** `typings/vue.d.ts`: the components for Vue's `GlobalComponents` (templates type-check props and events). */
function vue(models: Model[]): string {
  const imports = unique(models.flatMap((m) => [...m.imports.attributes, ...m.imports.events]));
  const pascal = (tag: string): string =>
    tag.replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase());
  return [
    HEADER,
    'import type { DefineComponent, HTMLAttributes } from "vue";',
    `import type { ${imports.join(", ")} } from "@srctool/camouflage-core";\n`,
    'declare module "vue" {',
    "  interface GlobalComponents {",
    ...models.flatMap((m) => [
      `    ${pascal(m.tag)}: DefineComponent<HTMLAttributes & {`,
      ...attributeLines(m, "      "),
      ...m.events.map(
        (e) => `      "on${pascal(e.name).replace(/^Camo/, "Camo")}"?: (event: ${e.type}) => void;`,
      ),
      "    }>;",
    ]),
    "  }",
    "}\n",
    "export {};",
  ].join("\n");
}

const outputs = (models: Model[]): Record<string, string> => ({
  "packages/core/src/elements.ts": globals(models),
  "packages/core/typings/react.d.ts": react(models),
  "packages/core/typings/vue.d.ts": vue(models),
});

const models = elementsOf(generateManifest()).map(model);
let stale = false;
for (const [path, raw] of Object.entries(outputs(models))) {
  const file = `${root}${path}`;
  const body = await format(raw, { ...(await resolveConfig(file)), filepath: file });
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {
      // A missing file is as stale as a changed one.
    }
    if (current !== body) {
      console.error(`${path} is out of date; run \`pnpm typings\` and commit the result.`);
      stale = true;
    }
  } else {
    writeFileSync(file, body);
    console.warn(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
